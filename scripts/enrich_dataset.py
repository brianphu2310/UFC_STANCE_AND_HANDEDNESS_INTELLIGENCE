def enrich(clean: pd.DataFrame) -> pd.DataFrame:
    rng = np.random.default_rng(SEED)
    df = clean.copy()

    # Official stance drives the app; the project's Excel stance is kept for comparison.
    df["stance"] = df["stance_ufcstats"]
    df["stance_matches_project"] = df["stance"] == df["stance_project"]

    # estimated — dominant foot
    same = rng.random(len(df)) < P_FOOT_SAME_SIDE
    df["foot"] = np.where(same, df["hand"], df["hand"].map({"Right": "Left", "Left": "Right"}))

    # curated
    df["champion"] = df["fighter"].isin(CHAMPIONS)

    # derived — popularity index: percentile of UFC headline + title fights, blended with
    # UFC wins, rescaled 0–100. A proxy for star power, not a fan-survey number.
    head = df["headliner_index"].fillna(0).rank(pct=True)
    wins = df["ufc_wins"].fillna(0).rank(pct=True)
    df["popularity_index"] = ((0.7 * head + 0.3 * wins) * 100).round(0).astype(int)

    df["stance_hand"] = df["stance"] + " · " + df["hand"] + "-handed"
    df["foot_hand"] = df["foot"] + " foot · " + df["hand"] + " hand"
    df["ape_index"] = (df["reach_cm"] / df["height_cm"]).round(3)

    overrides = DATA / "fighter_overrides.csv"
    if overrides.exists():
        ov = pd.read_csv(overrides).set_index("fighter")
        df = df.set_index("fighter")
        df.update(ov)
        df = df.reset_index()
    return df


